function uniqueByNumber(values: Array<string | undefined>) {
  return [...new Set(values.filter((value): value is string => Boolean(value)))].sort(
    (a, b) => parseFloat(a.replace(",", ".")) - parseFloat(b.replace(",", ".")),
  );
}

export const WEIGHT_FILTER_BUCKETS = [
  { label: "30–40 г", min: 30, max: 40 },
  { label: "40–50 г", min: 40, max: 50 },
  { label: "50–60 г", min: 50, max: 60 },
  { label: "60–70 г", min: 60, max: 70 },
  { label: "70–100 г", min: 70, max: 100 },
  { label: "100+ г", min: 100, max: Infinity },
] as const;

export function parsePairWeightGrams(weight?: string) {
  if (!weight) return null;
  const nums = [...weight.matchAll(/(\d+(?:[.,]\d+)?)/g)].map((match) =>
    parseFloat(match[1].replace(",", ".")),
  );
  if (!nums.length) return null;
  if (nums.length === 1) return { min: nums[0], max: nums[0] };
  return { min: Math.min(nums[0], nums[1]), max: Math.max(nums[0], nums[1]) };
}

export function productMatchesWeightFilters(weight: string | undefined, selected: string[]) {
  if (!selected.length) return true;
  const range = parsePairWeightGrams(weight);
  if (!range) return false;
  return selected.some((label) => {
    const bucket = WEIGHT_FILTER_BUCKETS.find((item) => item.label === label);
    if (!bucket) return false;
    return range.min < bucket.max && range.max >= bucket.min;
  });
}

export function buildSpecFilters(list: Product[]) {
  return {
    length: uniqueByNumber(list.map((p) => p.length)),
    weight: WEIGHT_FILTER_BUCKETS.map((bucket) => bucket.label),
    tex: uniqueByNumber(list.map((p) => p.tex)),
    knitClass: uniqueByNumber(list.map((p) => p.knitClass)),
  };
}

